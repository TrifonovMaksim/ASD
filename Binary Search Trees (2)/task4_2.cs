        // Задание 2. Поиск наименьшего общего предка (LCA).
        public int? FindLCA(int key1, int key2)
        {
            int? Key1Index = FindKeyIndex(key1);
            int? Key2Index = FindKeyIndex(key2);
            if (Key1Index == null || Key2Index == null || Key1Index < 0 || Key2Index < 0) return null;
            int index1 = Key1Index.Value;
            int index2 = Key2Index.Value;
            while (index1 != index2)
            {
                if (index1 > index2) index1 = (index1 - 1) / 2;
                else index2 = (index2 - 1) / 2;
            }
            return Tree[index1];
        }
        /* В массиве проще поиск, так-как мы через формулу родителя по мндексам, легко можем найти его без движения по ссылкам.
         * Сложность по времени O(depth) максимум пройдем от самого глубого уровня до корня.
         * Сложность по памяти O(1) ничего не создаем.
         */

