        public List<int> WideAllNodes()
        {
            List<int> ResNodes = new List<int>();
            for (int i = 0; i < Tree.Length;  i++)
            {
                if (Tree[i] != null) ResNodes.Add(Tree[i].Value);
            }
            return ResNodes;
        }
