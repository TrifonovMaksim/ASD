        {
            if (HeapArray == null || SecondHeap == null) return;
            if (HeapArray.Length - Count < SecondHeap.Count) return;
            int SecondHeapCount = SecondHeap.Count;
            for (int i = 0; i < SecondHeapCount; i++) Add((SecondHeap.GetMax()));
        }
