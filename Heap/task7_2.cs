        public int FindMaxInRange(int min, int max)
        {
            if (HeapArray == null || Count == 0) return default(int);
            return DoFindMaxInRange(0, min, max);
        }

        public int DoFindMaxInRange(int index, int min, int max)
        {
            if (index >= Count) return default(int);
            if (HeapArray[index] < min) return default(int);
            if (HeapArray[index] <= max) return HeapArray[index];
            if (HeapArray[index] > max)
            {
                int LeftChildMax = DoFindMaxInRange(2 * index + 1, min, max);
                int RightChildMax = DoFindMaxInRange(2 * index + 2, min, max);
                return Math.Max(LeftChildMax, RightChildMax);
            }
            return default(int);
        }

        /* Начинаем с корня, если корень меньше минимума, значит искомого в куче впринципе нет,
